using System.Text;
using System.Text.Json;
using MiniLeague.Engine.AI;
using MiniLeague.Engine.Models;
using MiniLeague.Engine.Services;
using MiniLeague.Engine.Simulation;

namespace MiniLeague.ManagerBench;

/// <summary>What one team did over every game it played in a calibration run.</summary>
public sealed class TeamTally
{
    public int Games, RunsFor, RunsAgainst, AB, H, D2, D3, HR, BB, SO, HBP, SB, CS, SH, DoublePlays, Errors;
    public int CompleteGames, PitchersUsed, StarterOuts, StarterPitches, IntentionalWalks;
    public int PitcherPlateAppearances, PitcherSacrifices, DoublePlayChances, GroundDoublePlays;
    public int Pitches, BattersFaced, Starts130, Starts150, MostPitches;
}

public sealed record CalibrationOptions(int GamesPerMatchup = 10, int Seed = 1, string Persona = "analyst",
    DesignatedHitterSetting DesignatedHitter = DesignatedHitterSetting.Historical);

/// <summary>
/// Calibration: plays every team against each of the others (home and away) with one computer manager on both sides,
/// and compares what each team did with what the real team did that season (lahman-reference.json, generated by
/// tools/export_lahman_reference.py).
/// WHY: the manager benchmark compares managers with each other; this asks whether the engine they all play in
/// reproduces the real game. A real team's numbers are against its own league, so a gap that is the same for every
/// team is the engine, and a gap that follows one team is that team's data.
/// </summary>
public static class Calibration
{
    public static Dictionary<string, TeamTally> Run(CalibrationOptions options)
    {
        string dir = Path.Combine(ManagerBenchmark.FindRepoRoot(), "src", "MiniLeague.Web", "wwwroot", "data", "teams");
        var files = Directory.GetFiles(dir, "*.json").OrderBy(f => f, StringComparer.Ordinal).ToList();
        var json = files.ToDictionary(f => f, File.ReadAllText);
        var ids = files.Select(f => Path.GetFileNameWithoutExtension(f)).ToList();
        var tallies = ids.ToDictionary(id => id, _ => new TeamTally());

        int n = 0, chances = 0, doublePlays = 0, groundOuts = 0;
        var starts = new Dictionary<string, Dictionary<int, int>>();   // team id -> pitcher id -> starts so far in this run
        for (int v = 0; v < files.Count; v++)
        for (int h = 0; h < files.Count; h++)
        {
            if (v == h) continue;
            for (int g = 0; g < options.GamesPerMatchup; g++, n++)
            {
                int seed = options.Seed + n;
                var game = new GameService(new AtBatResolver(new Random(seed)), new ComputerManager(new Random(seed)),
                    new Random(seed), ManagerCatalog.Default, managerSeed: seed);
                var visitor = TeamLoader.Parse(json[files[v]]);
                var home = TeamLoader.Parse(json[files[h]]);
                game.StartGame(visitor, home, ManagerControl.Computer, ManagerControl.Computer,
                    options: GameOptions.None with { DesignatedHitter = options.DesignatedHitter },
                    visitorStarterId: NextStarter(visitor, ids[v], starts), homeStarterId: NextStarter(home, ids[h], starts),
                    visitorManagerId: options.Persona, homeManagerId: options.Persona);
                var s = game.State!;
                int visitorWalks = 0, homeWalks = 0;
                for (int guard = 0; s.Status == GameStatus.InProgress && guard < 4000; guard++)
                {
                    bool top = s.IsTopOfInning;
                    // WHY: the double-play rate is per chance (a runner on first, fewer than two out), not per game: a team that
                    // gets fewer runners on turns fewer, and that is a different thing to fix from the odds on each ground ball.
                    bool chance = s.RunnerOnFirst is not null && s.Outs < 2;
                    var play = game.ExecuteComputerTurn();
                    if (play is null) break;
                    if (chance) { chances++; if (play.OutsRecorded >= 2) doublePlays++; if (play.Outcome == OutcomeType.GroundOut) groundOuts++; }
                    // The fielding side made the call: the home side fields in the top half.
                    if (game.LastDefense!.IntentionalWalk) { if (top) homeWalks++; else visitorWalks++; }
                }
                Add(tallies[ids[v]], s, visitor: true, s.VisitorTotalScore, s.HomeTotalScore, visitorWalks);
                Add(tallies[ids[h]], s, visitor: false, s.HomeTotalScore, s.VisitorTotalScore, homeWalks);
            }
        }
        DoublePlayCounts = (chances, doublePlays, groundOuts);
        return tallies;
    }

    /// <summary>
    /// Whose turn it is to start: the starter furthest behind his share of the team's real games started.
    /// WHY: the game's default starter is the ace, and a real team's numbers came from its whole rotation. Starting the ace every
    /// game made every opponent's pitching far better than it was (an ace walked 0.69 of his league's rate where the rotation
    /// walked 0.80), which showed as too few walks and too many strikeouts.
    /// </summary>
    public static int NextStarter(Team team, string id, Dictionary<string, Dictionary<int, int>> starts)
    {
        var rotation = team.Pitchers.Where(p => p.Role == PitcherRole.Starter).ToList();
        if (rotation.Count == 0) return team.DefaultStarter.Id;
        if (!starts.TryGetValue(id, out var used)) starts[id] = used = [];
        // A file with no games started shares the starts evenly.
        double Share(Player p) => Math.Max(p.PitchingOverall?.GamesStarted ?? 0, 1);
        double total = rotation.Sum(Share);
        int played = used.Values.Sum() + 1;
        var next = rotation.MaxBy(p => played * Share(p) / total - used.GetValueOrDefault(p.Id))!;
        used[next.Id] = used.GetValueOrDefault(next.Id) + 1;
        return next.Id;
    }

    /// <summary>How hard the pitchers were worked: pitches per batter faced, and how often a start ran long.</summary>
    public static string Workload(Dictionary<string, TeamTally> tallies)
    {
        var all = tallies.Values;
        double games = all.Sum(t => t.Games);
        return $"workload: {(double)all.Sum(t => t.Pitches) / Math.Max(all.Sum(t => t.BattersFaced), 1):F2} pitches a batter faced; " +
               $"starts of 130+ pitches {all.Sum(t => t.Starts130) / games:P1}, of 150+ {all.Sum(t => t.Starts150) / games:P1}, longest {all.Max(t => t.MostPitches)}";
    }

    /// <summary>Over the last run: chances (runner on first, fewer than two out), double plays on them, and ground outs on them.</summary>
    public static (int Chances, int DoublePlays, int GroundOuts) DoublePlayCounts { get; private set; }

    private static void Add(TeamTally t, GameState s, bool visitor, int runsFor, int runsAgainst, int intentionalWalks)
    {
        var box = visitor ? s.Box.Visitor : s.Box.Home;
        t.Games++;
        t.RunsFor += runsFor;
        t.RunsAgainst += runsAgainst;
        t.AB += box.Batters.Sum(b => b.AB); t.H += box.Batters.Sum(b => b.H);
        t.D2 += box.Batters.Sum(b => b.D2); t.D3 += box.Batters.Sum(b => b.D3); t.HR += box.Batters.Sum(b => b.HR);
        t.BB += box.Batters.Sum(b => b.BB); t.SO += box.Batters.Sum(b => b.SO); t.HBP += box.Batters.Sum(b => b.HBP);
        t.SB += box.Batters.Sum(b => b.SB); t.CS += box.Batters.Sum(b => b.CS); t.SH += box.Batters.Sum(b => b.SH);
        t.DoublePlays += box.DoublePlays;
        // WHY: a pitcher batting (no designated hitter) is where most sacrifices came from, so he is counted apart.
        var team = visitor ? s.VisitorTeam : s.HomeTeam;
        var pitchers = team.Roster.Where(p => p.IsPitcher).Select(p => p.Id).ToHashSet();
        foreach (var b in box.Batters.Where(b => pitchers.Contains(b.PlayerId)))
        {
            t.PitcherPlateAppearances += b.AB + b.BB + b.HBP + b.SH;
            t.PitcherSacrifices += b.SH;
        }
        t.Errors += box.Errors;
        t.IntentionalWalks += intentionalWalks;
        t.PitchersUsed += box.Pitchers.Count;
        if (box.Pitchers.Count == 1) t.CompleteGames++;
        t.StarterOuts += box.Pitchers.Count > 0 ? box.Pitchers[0].Outs : 0;
        t.StarterPitches += box.Pitchers.Count > 0 ? box.Pitchers[0].Pitches : 0;
        // WHY: a plausible rate of long outings is a check of its own: outs a start can be right while a few men throw 180.
        t.Pitches += box.Pitchers.Sum(p => p.Pitches);
        t.BattersFaced += box.Pitchers.Sum(p => p.BF);
        int starter = box.Pitchers.Count > 0 ? box.Pitchers[0].Pitches : 0;
        if (starter >= 130) t.Starts130++;
        if (starter >= 150) t.Starts150++;
        t.MostPitches = Math.Max(t.MostPitches, starter);
    }

    /// <summary>One measure: the real rate per game from the reference file and the simulated one.</summary>
    public sealed record Row(string Team, string Metric, double Real, double Sim)
    {
        public double Ratio => Real == 0 ? double.NaN : Sim / Real;
    }

    public static List<Row> Compare(Dictionary<string, TeamTally> tallies, string referenceJson)
    {
        using var doc = JsonDocument.Parse(referenceJson);
        var rows = new List<Row>();
        foreach (var team in doc.RootElement.GetProperty("teams").EnumerateArray())
        {
            string id = team.GetProperty("id").GetString()!;
            if (!tallies.TryGetValue(id, out var t) || t.Games == 0) continue;
            var season = team.GetProperty("season");
            var bat = team.GetProperty("batting");
            var rates = team.GetProperty("rates");
            double g = season.GetProperty("G").GetDouble();
            double Real(JsonElement e, string name) => e.GetProperty(name).GetDouble() / g;
            double Sim(int v) => (double)v / t.Games;
            void Add(string metric, double real, double sim) => rows.Add(new Row(id, metric, real, sim));

            Add("runs", Real(season, "R"), Sim(t.RunsFor));
            Add("runs allowed", Real(season, "RA"), Sim(t.RunsAgainst));
            Add("at-bats", Real(bat, "AB"), Sim(t.AB));
            Add("hits", Real(bat, "H"), Sim(t.H));
            Add("doubles", Real(bat, "2B"), Sim(t.D2));
            Add("triples", Real(bat, "3B"), Sim(t.D3));
            Add("home runs", Real(bat, "HR"), Sim(t.HR));
            Add("walks", Real(bat, "BB"), Sim(t.BB));
            Add("strikeouts", Real(bat, "SO"), Sim(t.SO));
            Add("steals", Real(season, "SB"), Sim(t.SB));
            Add("caught stealing", Real(season, "CS"), Sim(t.CS));
            // WHY: steals are the product of how often a team tries and how often it succeeds; they fail for different reasons.
            double realTries = season.GetProperty("SB").GetDouble() + season.GetProperty("CS").GetDouble();
            Add("steal attempts", realTries / g, Sim(t.SB + t.CS));
            if (realTries > 0 && t.SB + t.CS > 0)
                Add("steal success", season.GetProperty("SB").GetDouble() / realTries, (double)t.SB / (t.SB + t.CS));
            Add("double plays", Real(season, "DP"), Sim(t.DoublePlays));
            Add("errors", Real(season, "E"), Sim(t.Errors));
            Add("complete games", Real(season, "CG"), Sim(t.CompleteGames));
            Add("pitchers used", rates.GetProperty("pitchersPerGame").GetDouble(), Sim(t.PitchersUsed));
            if (bat.TryGetProperty("SH", out var sh) && sh.ValueKind == JsonValueKind.Number)
                Add("sacrifices", sh.GetDouble() / g, Sim(t.SH));
            Add("outs per start", rates.GetProperty("outsPerStart").GetDouble(), (double)t.StarterOuts / t.Games);
        }
        return rows;
    }

    public static string Report(List<Row> rows, int games, double pitchesPerStart = 0, double outsPerStart = 0, int pitcherPa = 0, int pitcherSh = 0)
    {
        var sb = new StringBuilder();
        sb.AppendLine($"Calibration: {games} team-games. Per game; ratio = simulated / real.");
        sb.AppendLine();
        var metrics = rows.Select(r => r.Metric).Distinct().ToList();
        foreach (var metric in metrics)
        {
            var mine = rows.Where(r => r.Metric == metric).ToList();
            sb.AppendLine($"{metric}: median ratio {Median(mine.Select(r => r.Ratio)):F2}, range {mine.Min(r => r.Ratio):F2} to {mine.Max(r => r.Ratio):F2}");
        }
        sb.AppendLine();
        sb.AppendLine($"pitchers batting: {(double)pitcherPa / Math.Max(games, 1):F2} plate appearances a team game, {(double)pitcherSh / Math.Max(games, 1):F3} sacrifices a team game");
        sb.AppendLine($"starters: {pitchesPerStart:F1} pitches and {outsPerStart:F1} outs a start ({pitchesPerStart / Math.Max(outsPerStart, 1):F2} pitches an out)");
        sb.AppendLine();
        sb.Append($"{"team",-10}");
        foreach (var metric in metrics) sb.Append($"{Short(metric),7}");
        sb.AppendLine();
        foreach (var team in rows.Select(r => r.Team).Distinct())
        {
            sb.Append($"{team,-10}");
            foreach (var metric in metrics)
            {
                var r = rows.FirstOrDefault(x => x.Team == team && x.Metric == metric);
                sb.Append(r is null || double.IsNaN(r.Ratio) ? $"{"-",7}" : $"{r.Ratio,7:F2}");
            }
            sb.AppendLine();
        }
        return sb.ToString();
    }

    private static string Short(string metric) => metric switch
    {
        "runs" => "R", "runs allowed" => "RA", "at-bats" => "AB", "hits" => "H", "doubles" => "2B", "triples" => "3B", "home runs" => "HR",
        "walks" => "BB", "strikeouts" => "SO", "steals" => "SB", "caught stealing" => "CS", "steal attempts" => "SBA", "steal success" => "SB%", "double plays" => "DP",
        "errors" => "E", "complete games" => "CG", "pitchers used" => "P/G", "sacrifices" => "SH", "outs per start" => "O/GS",
        _ => metric,
    };

    private static double Median(IEnumerable<double> values)
    {
        var v = values.Where(x => !double.IsNaN(x)).OrderBy(x => x).ToList();
        return v.Count == 0 ? double.NaN : v.Count % 2 == 1 ? v[v.Count / 2] : (v[v.Count / 2 - 1] + v[v.Count / 2]) / 2;
    }
}
